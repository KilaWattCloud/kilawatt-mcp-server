// Generates docs/TOOLS.md from the tool definitions the server returns for
// tools/list, so the reference cannot drift from the code.
//
//   npm run docs                                  write docs/TOOLS.md
//   node scripts/generate-tools-doc.js --check    fail if docs/TOOLS.md is stale
//
// The server is started with test/mock-fetch.js so no network call is possible.

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { McpProcess, root } from "../test/mcp-process.js";

const OUTPUT = resolve(root, "docs/TOOLS.md");

async function listTools() {
  // An empty API key and test endpoints keep the server away from real
  // accounts. tools/list makes no HTTP request.
  const server = new McpProcess({
    KILAWATT_API_KEY: "",
    KILAWATT_SITE_URL: "https://site.test",
    KILAWATT_BASE_URL: "https://gateway.test/api/public/v1",
    KILAWATT_X402_URL: "https://x402.test/exec",
  });
  try {
    await server.initialize();
    const response = await server.request("tools/list");
    if (response.error) throw new Error(response.error.message);
    return response.result.tools;
  } finally {
    await server.stop();
  }
}

const cell = (value) => String(value).replace(/[\\|]/g, "\\$&").replace(/\n/g, " ");
const code = (value) => `\`${typeof value === "string" ? value : JSON.stringify(value)}\``;

function allowedValues(schema) {
  const parts = [];
  if (schema.enum) parts.push(schema.enum.map(code).join(", "));
  if (schema.const !== undefined) parts.push(`must be ${code(schema.const)}`);
  if (schema.minimum !== undefined) parts.push(`minimum ${schema.minimum}`);
  if (schema.exclusiveMinimum !== undefined) parts.push(`greater than ${schema.exclusiveMinimum}`);
  if (schema.maximum !== undefined) parts.push(`maximum ${schema.maximum}`);
  if (schema.minLength !== undefined) parts.push(`at least ${schema.minLength} characters`);
  if (schema.maxLength !== undefined) parts.push(`at most ${schema.maxLength} characters`);
  if (schema.pattern !== undefined) parts.push(`pattern ${code(schema.pattern)}`);
  return parts.join("; ");
}

function annotationsLine(annotations = {}) {
  const hints = Object.entries(annotations).map(([key, value]) => `${code(key)}: ${code(value)}`);
  return hints.length ? `Annotations: ${hints.join(", ")}` : "Annotations: none";
}

function renderTool(tool) {
  const lines = [`## \`${tool.name}\``, "", tool.description, "", annotationsLine(tool.annotations), ""];
  const properties = Object.entries(tool.inputSchema?.properties ?? {});
  if (properties.length === 0) {
    lines.push("No parameters.", "");
    return lines.join("\n");
  }
  const required = new Set(tool.inputSchema.required ?? []);
  lines.push(
    "| Parameter | Type | Required | Default | Allowed values | Description |",
    "|-----------|------|----------|---------|----------------|-------------|",
  );
  for (const [name, schema] of properties) {
    lines.push(
      `| ${[
        code(name),
        schema.type ?? "",
        required.has(name) ? "Yes" : "No",
        schema.default === undefined ? "" : code(schema.default),
        allowedValues(schema),
        schema.description ?? "",
      ].map(cell).join(" | ")} |`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

function render(tools) {
  return [
    "# Tools",
    "",
    "<!-- Generated by `npm run docs` from the tool definitions in the code. Do not edit by hand. -->",
    "",
    `The server exposes ${tools.length} tools. Each section below is taken from the definitions the server returns for \`tools/list\`.`,
    "",
    ...tools.map((tool) => `- [\`${tool.name}\`](#${tool.name})`),
    "",
    ...tools.map(renderTool),
  ].join("\n");
}

const markdown = render(await listTools());

if (process.argv.includes("--check")) {
  const current = await readFile(OUTPUT, "utf8").catch(() => "");
  if (current !== markdown) {
    console.error("docs/TOOLS.md is out of date. Run npm run docs and commit the result.");
    process.exit(1);
  }
  console.log("docs/TOOLS.md is up to date.");
} else {
  await writeFile(OUTPUT, markdown);
  console.log(`Wrote docs/TOOLS.md (${markdown.length} bytes).`);
}
